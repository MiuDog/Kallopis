const _stringKeys = <String>{
  'sansFamily',
  'sansFallback',
  'monoFamily',
  'monoFallback',
  'uiFamily',
  'bodyFamily',
  'codeFamily',
};
const _numberKeys = <String>{
  'micro',
  'caption',
  'sub',
  'body',
  'lead',
  'h4',
  'h3',
  'h2',
  'h1',
  'display',
  'label',
