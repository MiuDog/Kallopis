const _weightKeys = <String>{
  'regular',
  'medium',
  'semiBold',
  'bold',
  'extraBold',
  'strong',
};

KlpTypographyTheme decodeTypography(KlpJsonMap json, KlpTypographyTheme base) {
  const path = 'typography';
  rejectUnknown(json, {..._stringKeys, ..._numberKeys, ..._weightKeys}, path);
  return KlpTypographyTheme(
    sansFamily: readString(json, 'sansFamily', path, base.sansFamily),
    sansFallback: readStrings(json, 'sansFallback', path, base.sansFallback),
    monoFamily: readString(json, 'monoFamily', path, base.monoFamily),
    monoFallback: readStrings(json, 'monoFallback', path, base.monoFallback),
    uiFamily: readString(json, 'uiFamily', path, base.uiFamily),
    bodyFamily: readString(json, 'bodyFamily', path, base.bodyFamily),
    codeFamily: readString(json, 'codeFamily', path, base.codeFamily),
    micro: readDouble(json, 'micro', path, base.micro),
    caption: readDouble(json, 'caption', path, base.caption),
    sub: readDouble(json, 'sub', path, base.sub),
    body: readDouble(json, 'body', path, base.body),
    lead: readDouble(json, 'lead', path, base.lead),
    h4: readDouble(json, 'h4', path, base.h4),
    h3: readDouble(json, 'h3', path, base.h3),
    h2: readDouble(json, 'h2', path, base.h2),
    h1: readDouble(json, 'h1', path, base.h1),
    display: readDouble(json, 'display', path, base.display),
    label: readDouble(json, 'label', path, base.label),
    section: readDouble(json, 'section', path, base.section),
    headingSmall: readDouble(json, 'headingSmall', path, base.headingSmall),
    heading: readDouble(json, 'heading', path, base.heading),
    title: readDouble(json, 'title', path, base.title),
    microLeading: readDouble(json, 'microLeading', path, base.microLeading),
    captionLeading: readDouble(
      json,
      'captionLeading',
      path,
      base.captionLeading,
    ),
    subLeading: readDouble(json, 'subLeading', path, base.subLeading),
    bodyLeading: readDouble(json, 'bodyLeading', path, base.bodyLeading),
    leadLeading: readDouble(json, 'leadLeading', path, base.leadLeading),
    h4Leading: readDouble(json, 'h4Leading', path, base.h4Leading),
    h3Leading: readDouble(json, 'h3Leading', path, base.h3Leading),
    h2Leading: readDouble(json, 'h2Leading', path, base.h2Leading),
    h1Leading: readDouble(json, 'h1Leading', path, base.h1Leading),
    displayLeading: readDouble(
      json,
      'displayLeading',
      path,
      base.displayLeading,
    ),
    headingLeading: readDouble(
      json,
      'headingLeading',
      path,
      base.headingLeading,
    ),
    codeLeading: readDouble(json, 'codeLeading', path, base.codeLeading),
    readingLeading: readDouble(
      json,
      'readingLeading',
      path,
      base.readingLeading,
    ),
    labelLeading: readDouble(json, 'labelLeading', path, base.labelLeading),
    labelTracking: readDouble(json, 'labelTracking', path, base.labelTracking),
    displayTracking: readDouble(
      json,
      'displayTracking',
      path,
      base.displayTracking,
    ),
    regular: readFontWeight(json, 'regular', path, base.regular),
    medium: readFontWeight(json, 'medium', path, base.medium),
    semiBold: readFontWeight(json, 'semiBold', path, base.semiBold),
    bold: readFontWeight(json, 'bold', path, base.bold),
    extraBold: readFontWeight(json, 'extraBold', path, base.extraBold),
    strong: readFontWeight(json, 'strong', path, base.strong),
  );
}

